<?php
/**
 * Simple PDF Generation Fallback
 * When other PDF libraries are not available
 */

if ( ! class_exists( 'CRG_PDF_Simple' ) ) {

class CRG_PDF_Simple {
    
    /**
     * Generate PDF using the best available method
     */
    public static function generate_pdf( $post_id ) {
        $data = CRG_Render::get_data( $post_id );
        
        // Method 1: Try Dompdf with HTML template
        if ( class_exists( 'Dompdf\\Dompdf' ) ) {
            return self::generate_with_dompdf( $data, $post_id );
        }
        
        // Method 2: Use existing render method if available
        if ( method_exists( 'CRG_Render', 'output_pdf_dompdf' ) ) {
            return CRG_Render::output_pdf_dompdf( $post_id );
        }
        
        // Method 3: Fallback to simple PDF
        return self::generate_simple_pdf( $data, $post_id );
    }
    
    /**
     * Generate PDF using Dompdf with HTML template
     */
    private static function generate_with_dompdf( $data, $post_id ) {
        try {
            // Get HTML content
            ob_start();
            CRG_Render::render_report_html( $data, true );
            $html = ob_get_clean();
            
            // Create PDF with Dompdf
            $dompdf = new \Dompdf\Dompdf();
            $dompdf->set_option( 'isHtml5ParserEnabled', true );
            $dompdf->set_option( 'isRemoteEnabled', true );
            $dompdf->loadHtml( $html );
            $dompdf->setPaper( 'A4', 'portrait' );
            $dompdf->render();
            
            // Output
            $filename = 'cleanup-report-' . $post_id . '-' . date( 'Y-m-d' ) . '.pdf';
            $dompdf->stream( $filename, array( 'Attachment' => true ) );
            exit;
            
        } catch ( Exception $e ) {
            // Log error and fallback
            error_log( 'PDF Generation Error: ' . $e->getMessage() );
            return self::generate_simple_pdf( $data, $post_id );
        }
    }
    
    /**
     * Generate simple text-based PDF
     */
    private static function generate_simple_pdf( $data, $post_id ) {
        // Create text content
        $content = [];
        $content[] = $data['title'] . ' - Cleanup Report';
        $content[] = '';
        $content[] = 'Date: ' . ( $data['date'] ?: date( 'F j, Y' ) );
        $content[] = 'Client: ' . ( $data['client'] ?: 'N/A' );
        $content[] = 'Site: ' . ( $data['site'] ?: 'N/A' );
        $content[] = 'Generated By: ' . $data['brand']['name'];
        $content[] = '';
        $content[] = 'SECURITY SUMMARY:';
        $content[] = 'Critical Issues: ' . $data['s_critical'];
        $content[] = 'Medium Issues: ' . $data['s_medium'];
        $content[] = 'Low Issues: ' . $data['s_low'];
        $content[] = 'Total Issues: ' . ( $data['s_critical'] + $data['s_medium'] + $data['s_low'] );
        
        if ( !empty( $data['infection_summary'] ) ) {
            $content[] = '';
            $content[] = 'INFECTION SUMMARY:';
            $content[] = $data['infection_summary'];
        }
        
        if ( !empty( $data['actions'] ) ) {
            $content[] = '';
            $content[] = 'ACTION ITEMS:';
            foreach ( $data['actions'] as $action ) {
                $content[] = '[' . $action['level'] . '] ' . $action['text'];
            }
        }
        
        if ( !empty( $data['highlights'] ) ) {
            $content[] = '';
            $content[] = 'CLEANUP HIGHLIGHTS:';
            $content[] = $data['highlights'];
        }
        
        $content[] = '';
        $content[] = 'Generated on ' . date( 'Y-m-d H:i:s' );
        
        // Create basic PDF
        $pdf_content = self::create_basic_pdf( $content );
        
        // Output
        header( 'Content-Type: application/pdf' );
        header( 'Content-Disposition: attachment; filename="cleanup-report-' . $post_id . '-' . date( 'Y-m-d' ) . '.pdf"' );
        header( 'Content-Length: ' . strlen( $pdf_content ) );
        echo $pdf_content;
        exit;
    }
    
    /**
     * Create a basic PDF structure
     */
    private static function create_basic_pdf( $content_lines ) {
        // PDF header
        $pdf = "%PDF-1.4\n";
        
        // Object 1: Catalog
        $pdf .= "1 0 obj\n<< /Type /Catalog /Pages 2 0 R >>\nendobj\n";
        
        // Object 2: Pages
        $pdf .= "2 0 obj\n<< /Type /Pages /Kids [3 0 R] /Count 1 >>\nendobj\n";
        
        // Create content stream
        $stream = "BT\n/F1 12 Tf\n50 750 Td\n";
        $max_lines = 45; // Fit about 45 lines per page
        $line_count = 0;
        
        foreach ( $content_lines as $line ) {
            if ( $line_count >= $max_lines ) break;
            
            // Handle empty lines
            if ( empty( trim( $line ) ) ) {
                $stream .= "0 -15 Td\n";
                $line_count++;
                continue;
            }
            
            // Escape line for PDF
            $escaped_line = self::escape_pdf_string( $line );
            $stream .= "(" . $escaped_line . ") Tj\n0 -15 Td\n";
            $line_count++;
        }
        
        $stream .= "ET";
        
        // Object 3: Page
        $pdf .= "3 0 obj\n<< /Type /Page /Parent 2 0 R /MediaBox [0 0 612 792] /Resources << /Font << /F1 4 0 R >> >> /Contents 5 0 R >>\nendobj\n";
        
        // Object 4: Font
        $pdf .= "4 0 obj\n<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>\nendobj\n";
        
        // Object 5: Content stream
        $pdf .= "5 0 obj\n<< /Length " . strlen( $stream ) . " >>\nstream\n" . $stream . "\nendstream\nendobj\n";
        
        // Cross-reference table
        $xref_pos = strlen( $pdf );
        $pdf .= "xref\n0 6\n";
        $pdf .= "0000000000 65535 f \n";
        $pdf .= "0000000009 00000 n \n";
        $pdf .= "0000000058 00000 n \n";
        $pdf .= "0000000115 00000 n \n";
        $pdf .= sprintf( "%010d 00000 n \n", strpos( $pdf, "4 0 obj" ) );
        $pdf .= sprintf( "%010d 00000 n \n", strpos( $pdf, "5 0 obj" ) );
        
        // Trailer
        $pdf .= "trailer\n<< /Size 6 /Root 1 0 R >>\nstartxref\n" . $xref_pos . "\n%%EOF";
        
        return $pdf;
    }
    
    /**
     * Escape string for PDF
     */
    private static function escape_pdf_string( $str ) {
        // Remove or replace problematic characters
        $str = str_replace( ['(', ')', '\\'], ['[', ']', '/'], $str );
        $str = preg_replace( '/[^\x20-\x7E]/', '?', $str ); // Replace non-ASCII
        return substr( $str, 0, 80 ); // Limit line length
    }
    
    /**
     * Check available PDF libraries
     */
    public static function get_available_libraries() {
        $available = [];
        
        if ( class_exists( 'Dompdf\\Dompdf' ) ) {
            $available[] = 'dompdf';
        }
        
        // Always have fallback
        $available[] = 'simple';
        
        return $available;
    }
    
    /**
     * Show admin notice about PDF status
     */
    public static function show_library_notice() {
        global $pagenow;
        
        // Only show on cleanup report pages
        if ( $pagenow !== 'edit.php' || ( $_GET['post_type'] ?? '' ) !== 'cleanup_report' ) {
            return;
        }
        
        $available = self::get_available_libraries();
        
        if ( in_array( 'dompdf', $available ) ) {
            echo '<div class="notice notice-success"><p><strong>PDF Export:</strong> Dompdf library detected - full HTML-to-PDF conversion available.</p></div>';
        } else {
            echo '<div class="notice notice-info"><p><strong>PDF Export:</strong> Using basic text-based PDF generation. Install Dompdf for enhanced formatting.</p></div>';
        }
    }
}

} // End class_exists check